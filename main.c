#include <avr/io.h>         // Подключение библиотеки для работы с портами ввода/вывода
#define F_CPU 11059200UL    // Определение частоты тактирования микроконтроллера 
#include <util/delay.h>     // Подключение библиотеки функций задержки
// Массив кодов для отображения цифр 0-9 на 7-сегментном индикаторе
const uint8_t numbers[] = {0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F};
// Функция извлечения цифры из числа по позиции
uint8_t digit(uint16_t d, uint8_t m){
    uint8_t i = 5, a;           // i - счетчик разрядов (5 разрядов), a - временная переменная
    while(i) // Цикл по всем разрядам числа
{                   
        a = d % 10;             // Получение младшего разряда (остаток от деления на 10)
        if(i-- == m) break;     // Если достигли нужного разряда - выход из цикла
        d /= 10;                // Уменьшение числа в 10 раз (переход к следующему разряду)
    }
    return(a);                  // Возврат найденной цифры
}
// Функция отображения числа на индикаторе
void disp(uint16_t num) // Функция отображения числа num на пятиразрядном семисегментном индикаторе
{
    uint8_t k; // Переменная-счётчик для перебора разрядов индикатора от 1 до 5
    uint8_t leading_zero = 1; // Флаг наличия незначащих нулей слева; 1 — нули пока не выводятся

    for (k = 1; k < 6; k++) // Цикл последовательного вывода всех пяти разрядов числа
    {
        uint8_t d = digit(num, k); // Получение цифры k-го разряда числа num с помощью функции digit()
        // Убираем незначащие нули слева
        if (d == 0 && leading_zero && k < 5) // Проверяем, является ли цифра нулём и находится ли она среди ведущих разрядов
        {
            PORTC = 0x00; // Передаём в PORTC нулевой код для отключения сегментов текущего разряда
        }
        else
        {
            leading_zero = 0; // Устанавливаем флаг в 0, так как встретилась значащая цифра
            PORTC = numbers[d]; // Передаём в PORTC код отображения полученной цифры
        }
        PORTA = 1 << k; // Устанавливаем единицу в соответствующий разряд PORTA для выбора текущего индикатора
        _delay_us(1); // Задержка 1 микросекунда для формирования сигнала LE и записи кода в регистр-защёлку
        PORTA = 0x00; // Сбрасываем PORTA и отключаем сигнал LE текущего разряда
    }
}
int main(){
    DDRA = 0b00111110;    // настройка портов А на выход
    DDRC = 0b01111111;    // настройка портов С на выход
        while (1) {       // Бесконечный основной цикл программы
        int i = 0;          // Счетчик для цикла отображения чисел
        uint16_t x = 4;     // Начальное значение для отображения
                for (i; i < 20; i++){ // Цикл от 0 до 19 (20 итераций)
            disp(x);            // Отображение текущего числа на индикаторе
            x += 2;             // Увеличение числа на 2
            _delay_ms(1000);    // Задержка 1000 мс (1 секунда)
                          }
            }
}
